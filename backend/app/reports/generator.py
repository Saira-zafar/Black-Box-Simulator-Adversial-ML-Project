"""
Security Report Generator.

Generates structured Markdown and JSON assessment reports complete with
executive summaries, technical evidence, CWE/OWASP mappings, and defensive remediation guidance.
"""

from typing import Dict, Any, List
import datetime
import os


def generate_security_report(
    run_id: str,
    scenario: Dict[str, Any],
    target_url: str,
    verdict: str,
    severity: str,
    duration_ms: float,
    step_results: List[Dict[str, Any]],
    summary: str
) -> Dict[str, Any]:
    """
    Constructs both Markdown and JSON representation of the security assessment.
    """
    now_utc = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    title = f"Security Assessment: {scenario.get('name')}"

    # Generate Markdown content
    md_lines = [
        f"# {title}",
        f"**Assessment ID:** `{run_id}`  ",
        f"**Date/Time:** {now_utc}  ",
        f"**Target System:** `{target_url}` *(Local Sandbox Verified)*  ",
        f"**Scope Constraint:** Local Testing Environment Only  \n",
        "---",
        "## 1. Executive Summary\n",
        "| Metric | Assessment Result |",
        "| :--- | :--- |",
        f"| **Overall Verdict** | **{verdict}** |",
        f"| **Assigned Severity** | **{severity}** |",
        f"| **Scenario Category** | {scenario.get('category')} |",
        f"| **CWE Classification** | `{scenario.get('cwe_id')}` |",
        f"| **OWASP Category** | `{scenario.get('owasp_category')}` |",
        f"| **Execution Duration** | {duration_ms:.2f} ms |",
        f"| **Total Steps Evaluated** | {len(step_results)} |",
        f"| **Failed Checks** | {len([s for s in step_results if s.get('verdict') == 'FAIL'])} |\n",
        f"> **Assessment Conclusion:**  \n> {summary}\n",
        "---",
        "## 2. Technical Evidence & Step-by-Step Findings\n"
    ]

    for step in step_results:
        status_badge = "✅ PASS" if step.get("verdict") == "PASS" else "❌ FAIL (Vulnerability Observed)"
        md_lines.extend([
            f"### Step {step.get('step_number')}: {step.get('step_name')}",
            f"- **Result:** {status_badge}",
            f"- **Observed Status Code:** `{step.get('http_status_code')}`",
            f"- **Expected Behavior:** {step.get('expected_behavior')}",
            f"- **Observed Behavior:** {step.get('observed_behavior')}\n",
            "**Request Details:**",
            "```json",
            str(step.get("request_dump", {})),
            "```\n",
            "**Response Details:**",
            "```json",
            str(step.get("response_dump", {})),
            "```\n"
        ])

    md_lines.extend([
        "---",
        "## 3. Defensive Remediation Guidance\n",
        f"### {scenario.get('name')} Remediation:",
        f"{scenario.get('remediation_guidance')}\n",
        "### Specific Action Items:"
    ])

    for step in step_results:
        if step.get("remediation_note"):
            md_lines.append(f"- **Step {step.get('step_number')}**: {step.get('remediation_note')}")

    md_lines.extend([
        "\n---",
        "*Report automatically generated by Black-Box Attack Simulator educational sandbox.*"
    ])

    markdown_report = "\n".join(md_lines)

    # JSON structured report
    json_report = {
        "report_id": run_id,
        "generated_at": now_utc,
        "title": title,
        "target_url": target_url,
        "verdict": verdict,
        "severity": severity,
        "duration_ms": duration_ms,
        "scenario": {
            "id": scenario.get("id"),
            "name": scenario.get("name"),
            "category": scenario.get("category"),
            "cwe_id": scenario.get("cwe_id"),
            "owasp_category": scenario.get("owasp_category")
        },
        "summary": summary,
        "step_results": step_results,
        "remediation_guidance": scenario.get("remediation_guidance")
    }

    # Save copy to disk in reports/ directory if accessible
    try:
        reports_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..", "reports"))
        os.makedirs(reports_dir, exist_ok=True)
        file_path = os.path.join(reports_dir, f"assessment_{run_id}.md")
        with open(file_path, "w", encoding="utf-8") as f:
            f.write(markdown_report)
    except Exception:
        pass

    return {
        "title": title,
        "format": "markdown",
        "content_markdown": markdown_report,
        "content_json": json_report
    }
